/* tools/doc/navgen.mjs — regenerate GAMES.md's "How to read this file" navigation
 * block IN PLACE (the parts table + the Measured-facts entry index).
 *
 * Why it exists: the block quotes line numbers, and inserting it shifts every
 * line below it — so hand-computed numbers are stale the moment they land.
 * This regenerates from the file as it is, iterating until the block's own
 * height stops moving (fixed point), so the quoted numbers are always true of
 * the file it is written into.
 *
 * Navigation layer ONLY: it reads the record and rewrites just the block
 * between its own header and the next `## ` heading. No entry text is touched.
 *
 * usage: node tools/doc/navgen.mjs [path/to/GAMES.md] [--check]
 *        --check = verify the quoted numbers are current, exit 1 if not
 *                  (no write) — for the post-edit verification step. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { historyFiles } from '../lib/docset.mjs';

const P = process.argv[2] && !process.argv[2].startsWith('--') ? process.argv[2] : 'docs/GAMES.md';
const CHECK = process.argv.includes('--check');
const HEAD = '## How to read this file';
const NOTE = '*Navigation layer, regenerated by `tools/doc/navgen.mjs` — over the whole record set (this file + `docs/history/`) — quotes line numbers, so re-run it after any edit that moves lines (it iterates to a fixed point; nothing else in any file is touched: no record was rewritten, retired or reworded to build it, and the era files are read-only inputs).*';
// B3C: the frozen era files are read-only inputs; only this file's block is written.
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const HIST = historyFiles(ROOT).map(f => {
  const t = readFileSync(path.join(ROOT, f), 'utf8');
  return { file: f, key: path.basename(f).replace(/\.md$/, ''), lines: t.split(/\r?\n/), bytes: Buffer.byteLength(t) };
});

const src = readFileSync(P, 'utf8');
const nl = src.includes('\r\n') ? '\r\n' : '\n';
let lines = src.split(/\r?\n/);

function sectionStarts(ls) {
  return ls.map((l, i) => (l.startsWith('## ') ? [i, l] : null)).filter(Boolean);
}

function entryBlocks(ls, mf, tr) {
  /* an entry = a line starting with '**' plus every following paragraph that
   * is not itself a new dated/titled entry */
  /* An entry heading is a line-leading bold span whose opening sentence carries
   * a date — `**Title (2026-10-22, …).** body`. Requiring the DATE is what keeps
   * an entry's own bolded sub-headings (**Bake:** …, **Promotion:** …) from
   * being mistaken for new entries. Entries are NOT reliably blank-separated in
   * this file (consecutive same-day entries can be adjacent lines), so the scan
   * treats every heading as a boundary whether or not a blank line precedes it —
   * the first version of this required a blank line and silently merged two
   * entries, reporting 41 of 42. */
  const isNew = l => {
    if (l.startsWith('### ')) return /\((20\d\d-\d\d-\d\d|owner)/.test(l);   // B3A: ### heading form
    if (!/^\*\*[^*]/.test(l)) return false;
    const c = l.indexOf('**', 2);
    if (c < 0) return false;
    return /\((20\d\d-\d\d-\d\d|owner)/.test(l.slice(0, c + 2));
  };
  const out = [];
  let i = mf + 1, open = -1;
  while (i < tr) {
    if (isNew(ls[i])) {
      if (open >= 0) out.push([open, i - 1]);
      open = i;
    } else if (open >= 0 && ls[i].startsWith('## ')) {
      out.push([open, i - 1]); open = -1;
    }
    i++;
  }
  if (open >= 0) out.push([open, tr - 1]);
  /* trim trailing blank lines off each block so the KB figure is the entry's */
  return out.map(([a, b]) => { while (b > a && !ls[b].trim()) b--; return [a, b]; });
}

const title = l => {
  let t = l.trim().replace(/^(?:\*\*|### )/, '').split('**')[0];   // B3A: ### heading form
  t = t.replace(/\s*\(20\d\d-\d\d-\d\d[\s\S]*$/, '').replace(/\s*\(owner[\s\S]*$/, '');
  return t.replace(/\s*[—\-·,]+\s*$/, '').trim().slice(0, 84);
};
/* B3E (#749): a numbered heading "### NNN - (date) text" is cut by title() at the date paren and
 * left a bare number in the index. For those titles only, keep the number and the heading's own separator and
 * append the heading text after the date group: word-boundary cut at 84 chars, never an open code span, pipes
 * escaped. Every other title is unchanged. */
const rowTitle = l => {
  const t = title(l);
  if (!/^\d+$/.test(t)) return t;
  const m = l.match(/^### (\d+)(\s+\S+\s+)\((?:20\d\d-\d\d-\d\d|owner)[^)]*\)\s*(.*)$/);
  if (!m) return t;
  const lead = m[1] + m[2], room = 84 - lead.length;
  let r = m[3].split('**')[0].trim();
  if (r.length > room) { r = r.slice(0, room); const sp = r.lastIndexOf(' '); if (sp > room * 0.6) r = r.slice(0, sp); }
  if ((r.match(/\x60/g) || []).length % 2) r = r.slice(0, r.lastIndexOf('\x60'));
  r = r.replace(/[\s,:;.\-\u2014\u00b7]+$/, '').replace(/\|/g, '\\|');
  return r ? lead + r : t;
};
const dateOf = blk => (blk.match(/\((20\d\d-\d\d-\d\d)/) || [, 'undated'])[1];
const kbOf = blk => { const k = Buffer.byteLength(blk) / 1024; return k >= 1 ? String(Math.round(k)) : '<1'; };

/* B3C: the Measured-facts span of a file = its '## Measured facts' heading up to the
 * next '## ' (in GAMES that is '## Testing recipe'; in an era file it is end of file). */
function mfSpan(ls) {
  const a = ls.findIndex(l => l.startsWith('## Measured facts'));
  if (a < 0) return null;
  let b = a + 1; while (b < ls.length && !ls[b].startsWith('## ')) b++;
  return [a, b];
}
const entriesOf = ls => { const sp = mfSpan(ls); return sp ? entryBlocks(ls, sp[0], sp[1]) : []; };

function build(ls) {
  const secs = sectionStarts(ls);
  const o = [];
  o.push(HEAD, '', NOTE, '', '**Parts** (this file)', '', '| section | from line | size |', '|---|---|---|');
  for (let k = 0; k < secs.length; k++) {
    const [i, t] = secs[k];
    const end = k + 1 < secs.length ? secs[k + 1][0] : ls.length;
    if (t === HEAD) continue;
    o.push(`| ${t.replace(/^\#\#\s*/, '').slice(0, 70)} | ${i + 1} | ${Math.round(Buffer.byteLength(ls.slice(i, end).join('\n')) / 1024)} KB |`);
  }
  if (HIST.length) {
    o.push('', '**Frozen eras** (`docs/history/` — grep only, never load whole; the key is what the entry index below uses)', '',
      '| key | file | covers | items | size |', '|---|---|---|---:|---|');
    for (const h of HIST) {
      const h1 = (h.lines.find(l => l.startsWith('# ')) || '# ' + h.key).slice(2);
      const n = entriesOf(h.lines).length || h.lines.filter(l => /^## 20\d\d-\d\d-\d\d/.test(l)).length;
      o.push(`| ${h.key} | \`${h.file}\` | ${h1.slice(0, 78)} | ${n} | ${Math.round(h.bytes / 1024)} KB |`);
    }
    o.push('', 'items = `###` measured-facts entries, or dated `##` landings for a chronicle file.');
  }
  /* B3C: one index over the whole record set — frozen eras in file order, then the live
   * file (new entries land in GAMES, so it is last). Line numbers are per file. */
  const sources = [...HIST.map(h => ({ key: h.key, lines: h.lines })), { key: 'GAMES', lines: ls }];
  const rows = []; let nfiles = 0;
  for (const s of sources) {
    const ents = entriesOf(s.lines);
    if (ents.length) nfiles++;
    for (const [a, b] of ents) {
      const blk = s.lines.slice(a, b + 1).join('\n');
      rows.push(`| ${s.key} | ${a + 1} | ${dateOf(blk)} | ${rowTitle(s.lines[a])} | ${kbOf(blk)} |`);
    }
  }
  o.push('', `**Measured facts — entry index** (${rows.length} entries in ${nfiles} file(s), oldest first; this is the largest part of the record, so the index is the way in. "file" = the key above, GAMES = this file; "line" = the entry's first line in that file.)`, '', '| file | line | date | entry | KB |', '|---|---|---|---|---|');
  o.push(...rows);
  o.push('', '---', '');
  return o;
}

/* splice: replace the existing block (or insert before '## Current state') */
function splice(ls, block) {
  const h = ls.indexOf(HEAD);
  if (h >= 0) {
    let e = h + 1;
    while (e < ls.length && !ls[e].startsWith('## ')) e++;
    return [...ls.slice(0, h), ...block, ...ls.slice(e)];
  }
  const c = ls.findIndex(l => l === '## Current state');
  if (c < 0) throw new Error('no insertion anchor');
  return [...ls.slice(0, c), ...block, ...ls.slice(c)];
}

let cur = lines, prev = null, guard = 0;
do {
  prev = cur;
  cur = splice(prev, build(prev));
} while (cur.join('\n') !== prev.join('\n') && ++guard < 8);

const out = cur.join(nl);
if (CHECK) {
  const ok = out === src;
  console.log(ok ? 'navgen --check: navigation block CURRENT' : 'navgen --check: navigation block STALE — re-run node tools/doc/navgen.mjs');
  process.exit(ok ? 0 : 1);
}
writeFileSync(P, out);
console.log(`navgen: wrote ${P} — block ${build(cur).length} lines, converged in ${guard + 1} pass(es), file ${Buffer.byteLength(out) / 1024 | 0} KB / ${cur.length} lines`);
