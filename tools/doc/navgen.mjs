/* scratch/navgen.mjs — regenerate GAMES.md's "How to read this file" navigation
 * block IN PLACE (the parts table + the Measured-facts entry index).
 *
 * Why it exists: the block quotes line numbers, and inserting it shifts every
 * line below it — so hand-computed numbers are stale the moment they land.
 * This regenerates from the file as it is, iterating until the block's own
 * height stops moving (fixed point), so the quoted numbers are always true of
 * the file it is written into.
 *
 * Navigation layer ONLY: it reads the record and rewrites just the block
 * between its own header and the next `## ` heading. No entry text is touched.
 *
 * usage: node scratch/navgen.mjs [path/to/GAMES.md] [--check]
 *        --check = verify the quoted numbers are current, exit 1 if not
 *                  (no write) — for the post-edit verification step. */
import { readFileSync, writeFileSync } from 'node:fs';

const P = process.argv[2] && !process.argv[2].startsWith('--') ? process.argv[2] : 'docs/GAMES.md';
const CHECK = process.argv.includes('--check');
const HEAD = '## How to read this file';
const NOTE = '*Navigation layer, regenerated by `scratch/navgen.mjs` — quotes line numbers, so re-run it after any edit that moves lines (it iterates to a fixed point; nothing else in the file is touched: no record was rewritten, retired or reworded to build it).*';

const src = readFileSync(P, 'utf8');
const nl = src.includes('\r\n') ? '\r\n' : '\n';
let lines = src.split(/\r?\n/);

function sectionStarts(ls) {
  return ls.map((l, i) => (l.startsWith('## ') ? [i, l] : null)).filter(Boolean);
}

function entryBlocks(ls, mf, tr) {
  /* an entry = a line starting with '**' plus every following paragraph that
   * is not itself a new dated/titled entry */
  /* An entry heading is a line-leading bold span whose opening sentence carries
   * a date — `**Title (2026-10-22, …).** body`. Requiring the DATE is what keeps
   * an entry's own bolded sub-headings (**Bake:** …, **Promotion:** …) from
   * being mistaken for new entries. Entries are NOT reliably blank-separated in
   * this file (consecutive same-day entries can be adjacent lines), so the scan
   * treats every heading as a boundary whether or not a blank line precedes it —
   * the first version of this required a blank line and silently merged two
   * entries, reporting 41 of 42. */
  const isNew = l => {
    if (!/^\*\*[^*]/.test(l)) return false;
    const c = l.indexOf('**', 2);
    if (c < 0) return false;
    return /\((20\d\d-\d\d-\d\d|owner)/.test(l.slice(0, c + 2));
  };
  const out = [];
  let i = mf + 1, open = -1;
  while (i < tr) {
    if (isNew(ls[i])) {
      if (open >= 0) out.push([open, i - 1]);
      open = i;
    } else if (open >= 0 && ls[i].startsWith('## ')) {
      out.push([open, i - 1]); open = -1;
    }
    i++;
  }
  if (open >= 0) out.push([open, tr - 1]);
  /* trim trailing blank lines off each block so the KB figure is the entry's */
  return out.map(([a, b]) => { while (b > a && !ls[b].trim()) b--; return [a, b]; });
}

const title = l => {
  let t = l.trim().replace(/^\*\*/, '').split('**')[0];
  t = t.replace(/\s*\(20\d\d-\d\d-\d\d[\s\S]*$/, '').replace(/\s*\(owner[\s\S]*$/, '');
  return t.replace(/\s*[—\-·,]+\s*$/, '').trim().slice(0, 84);
};
const dateOf = blk => (blk.match(/\((20\d\d-\d\d-\d\d)/) || [, 'undated'])[1];
const kbOf = blk => { const k = Buffer.byteLength(blk) / 1024; return k >= 1 ? String(Math.round(k)) : '<1'; };

function build(ls) {
  const secs = sectionStarts(ls);
  const get = p => { const h = secs.find(([, t]) => t.startsWith(p)); return h ? h[0] : null; };
  const mf = get('## Measured facts'), tr = get('## Testing recipe');
  if (mf === null || tr === null) throw new Error('section anchors not found');
  const o = [];
  o.push(HEAD, '', NOTE, '', '**Parts**', '', '| section | from line | size |', '|---|---|---|');
  for (let k = 0; k < secs.length; k++) {
    const [i, t] = secs[k];
    const end = k + 1 < secs.length ? secs[k + 1][0] : ls.length;
    if (t === HEAD) continue;
    o.push(`| ${t.replace(/^\#\#\s*/, '').slice(0, 70)} | ${i + 1} | ${Math.round(Buffer.byteLength(ls.slice(i, end).join('\n')) / 1024)} KB |`);
  }
  const ents = entryBlocks(ls, mf, tr);
  o.push('', `**Measured facts — entry index** (${ents.length} entries, oldest first; this section is the file's largest, so the index is the way in. "line" = the entry's first line.)`, '', '| line | date | entry | KB |', '|---|---|---|---|');
  for (const [a, b] of ents) {
    const blk = ls.slice(a, b + 1).join('\n');
    o.push(`| ${a + 1} | ${dateOf(blk)} | ${title(ls[a])} | ${kbOf(blk)} |`);
  }
  o.push('', '---', '');
  return o;
}

/* splice: replace the existing block (or insert before '## Current state') */
function splice(ls, block) {
  const h = ls.indexOf(HEAD);
  if (h >= 0) {
    let e = h + 1;
    while (e < ls.length && !ls[e].startsWith('## ')) e++;
    return [...ls.slice(0, h), ...block, ...ls.slice(e)];
  }
  const c = ls.findIndex(l => l === '## Current state');
  if (c < 0) throw new Error('no insertion anchor');
  return [...ls.slice(0, c), ...block, ...ls.slice(c)];
}

let cur = lines, prev = null, guard = 0;
do {
  prev = cur;
  cur = splice(prev, build(prev));
} while (cur.join('\n') !== prev.join('\n') && ++guard < 8);

const out = cur.join(nl);
if (CHECK) {
  const ok = out === src;
  console.log(ok ? 'navgen --check: navigation block CURRENT' : 'navgen --check: navigation block STALE — re-run node scratch/navgen.mjs');
  process.exit(ok ? 0 : 1);
}
writeFileSync(P, out);
console.log(`navgen: wrote ${P} — block ${build(cur).length} lines, converged in ${guard + 1} pass(es), file ${Buffer.byteLength(out) / 1024 | 0} KB / ${cur.length} lines`);
