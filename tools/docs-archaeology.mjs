#!/usr/bin/env node
/* tools/docs-archaeology.mjs — remove decision archaeology from a document's prose.
 *
 * WHY (audit finding W-02; owner ruling 2026-11-19). The repository's doctrine is "Current docs
 * state current rules; dated entries + git history hold history" - and §Current state of the design
 * record broke it: it was 22,204 tokens of design prose that still embedded dated narrative, owner
 * quotes and the record of approaches that were rejected. An agent grepping §Current state for a
 * current fact still had to skip 185 lines over the 300-character prose cap, and the worst of them
 * returned ~2,100 characters of history for one fact.
 *
 * The owner's ruling was explicit: "you are free to remove and delete all of that, an agent doesnt
 * need to know it." This tool applies that ruling to the prose of a markdown document, using the
 * SAME rule catalogue the canonical's comment layer uses (tools/lib/archaeology.mjs), so the two
 * surfaces cannot drift into different standards of what counts as archaeology.
 *
 * WHAT IT TOUCHES: prose lines only. It never touches a heading (a heading is a pointer other
 * documents resolve against), a table row (a table row is data), a fenced code block, or a generated
 * block. The WHAT survives - the decision, the law, the rationale - and the WHO/WHEN/WHAT-WAS-TRIED
 * goes.
 *
 * usage:
 *   node tools/docs-archaeology.mjs <file>            rewrite the prose in place
 *   node tools/docs-archaeology.mjs <file> --check    report what WOULD change; write nothing
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { derubLine, removeRawQuotes } from './lib/archaeology.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const FILE = args.find((a) => !a.startsWith('--'));
const CHECK = args.includes('--check');
if (!FILE) { console.error('usage: node tools/docs-archaeology.mjs <file> [--check]'); process.exit(2); }

const src = readFileSync(path.join(root, FILE), 'utf8');
const nl = src.includes('\r\n') ? '\r\n' : '\n';
const lines = src.split(/\r?\n/);

const out = [];
const changed = [];
let inFence = false, inGen = false, inNav = false, inEntry = false;
for (let i = 0; i < lines.length; i++) {
  const l = lines[i];
  if (/^\s*```/.test(l)) { inFence = !inFence; out.push(l); continue; }
  if (inFence) { out.push(l); continue; }
  if (/^<!-- BEGIN GENERATED /.test(l)) { inGen = true; out.push(l); continue; }
  if (/^<!-- END GENERATED /.test(l)) { inGen = false; out.push(l); continue; }
  if (inGen) { out.push(l); continue; }
  if (/^\s*\|/.test(l)) { out.push(l); continue; }      // a table row is data
  if (/^( {4}|\t)/.test(l)) { out.push(l); continue; }    // an INDENTED BLOCK is code: its spacing and
                                                        // its vocabulary are its own
  if (/^\s*(-{3,}|\*{3,}|_{3,})\s*$/.test(l)) { out.push(l); continue; }   // a thematic break is not prose
  if (/^## How to read this file/.test(l)) { inNav = true; out.push(l); continue; }
  /* A DATED ENTRY is where history lives - the repo's own doctrine is "Current docs state current
   * rules; dated entries + git history hold history". So the landing records keep their dates and
   * their quotes, and only the living sections are derubbed. */
  if (/^## \d{4}-\d{2}-\d{2}\b/.test(l)) { inEntry = true; out.push(l); continue; }
  if (inEntry && /^## /.test(l)) { inEntry = false; }
  if (inEntry) { out.push(l); continue; }
  if (inNav && /^## /.test(l)) { inNav = false; }
  if (inNav) { out.push(l); continue; }                   // the navigation layer is GENERATED by navgen
  if (/^#{1,6}\s/.test(l)) { out.push(l); continue; }    // a heading is a pointer other docs resolve against
  if (/^\s*>/.test(l)) { out.push(l); continue; }        // a blockquote line is handled as prose below

  /* A raw quote can span several lines, and the markdown continuation ("   * ") sits inside it. So
   * the quotes are removed over the whole LINE first; a quote that continues on the next line is
   * handled by the next line's own pass. */
  /* The leading whitespace of a continuation line is MARKDOWN (a list item's continuation), not
   * content, so it is detached before the rules run and re-attached after. Stripping it here would
   * silently re-indent the paragraph - the rules ran once and the file never settled. */
  const lead = l.match(/^[ \t]*/)[0];
  let t = removeRawQuotes(l.slice(lead.length));
  t = derubLine(t);
  t = t.replace(/^[:;]+\s*/, '');            // an orphaned leading colon, not the indentation, not a list marker
                                           // and not a path: ".qa/..." starts with a dot
  t = lead + t;
  if (t !== l) changed.push({ line: i + 1, before: l, after: t });
  out.push(t);
}

const joined = out.join(nl);
const beforeChars = lines.reduce((a, l) => a + l.length, 0);
const afterChars = joined.split(/\r?\n/).reduce((a, l) => a + l.length, 0);
console.log(`docs-archaeology: ${FILE} — ${changed.length} prose line(s) changed, ${beforeChars} → ${afterChars} chars (-${beforeChars - afterChars})`);
if (args.includes('--report')) for (const c of changed) console.log(`  L${c.line}\n    BEFORE: ${c.before.slice(0, 200)}\n    AFTER : ${c.after.slice(0, 200)}`);
if (CHECK) { console.log(`docs-archaeology --check: ${changed.length ? 'CHANGES PENDING' : 'clean'}`); process.exit(changed.length ? 1 : 0); }
writeFileSync(path.join(root, FILE), joined);
console.log(`wrote ${FILE}`);
