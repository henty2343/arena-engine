/* .qa/lengrow-bake.mjs — regenerate the per-step coverings in the canonical's LEN_CIRCLES block.
 *
 * WHY THIS EXISTS. The length-growth ladder stretches the spear along its spine with a rigid
 * piecewise map (shaft scales, head translates). Holding every circle's `l` and `r` while remapping
 * `d` keeps the art from thickening, but it also spreads the shaft circles apart as they scale, and
 * past **tip growth +39.5%** the deepest uncovered ink point passes inscribe.mjs's 4.6px MISS_TOL
 * (swept: `.qa/lengrow-gate.mjs --mode rigid`, last pass k=1.6469 miss 4.59, first fail +40% at
 * 4.61). The spear now grows to **+200%**, so the covering has to FOLLOW the growth: each step gets
 * its own covering, RE-PACKED by the house packer against that step's own stretched silhouette.
 *
 * That is this tool. It does not invent a packing algorithm — it drives the sanctioned one
 * (`.qa/bake-rows.mjs`, which calls inscribe.mjs's raster-EDT greedy union-inscribed regen, the
 * same packer that baked all 22 shipped rows). Measured result: miss 1.96-3.86px per step, BETTER
 * than the shipped base row's 4.25px, because a fresh pack fits the stretched silhouette instead of
 * inheriting the base row's spacing.
 *
 * ART AND CIRCLES AGREE, and here is the proof rather than the assertion. The stretch is injected
 * post-normalisation and PRE-weaponScale, while the ladder maps the BOOTED (post-weaponScale)
 * polys. Those coincide exactly because the map is homogeneous of degree 1 in (d, J): with
 * J = maxD * lenJ in both spaces and maxD_boot = 1.3 * maxD_ingr, map(1.3*d) = 1.3*map(d). So a row
 * baked against the stretched INGR art IS a row for the stretched booted art. `--verify` re-checks
 * this numerically instead of trusting it.
 *
 * Parameters are READ FROM THE CANONICAL (trait.len, lenJ, LEN_STEPS), never hardcoded here, so the
 * rows cannot drift from the row that uses them.
 *
 * WRITE SAFETY. Only the marked LEN_CIRCLES BEGIN/END block is ever replaced; everything else in
 * the file is byte-preserved. Baking runs on a scratch temp copy and the canonical is written only
 * after every step has baked. Never point this at anything but the canonical.
 *
 * Usage: node .qa/lengrow-bake.mjs                 print the block, write nothing (dry run)
 *        node .qa/lengrow-bake.mjs --write         replace the marked block in the canonical
 *        node .qa/lengrow-bake.mjs --verify        bake, then gate every step's row against its own art
 *        node .qa/lengrow-bake.mjs --emit FILE     write the block to FILE, touch nothing (lets a
 *                                                  code edit and a geometry edit land atomically)
 *        node .qa/lengrow-bake.mjs --steps N ...   PROBE a ladder taller than the canonical's
 *                                                  (refuses --write; --emit is allowed)
 *
 * SCOPE, deliberately narrow: this bakes LENGTH growth, and length is the spear's trait alone — the
 * owner's ruling is that max weapon length IS the spear's, so a second grower is not expected. The
 * GROWERS guard below fails loudly rather than silently baking one weapon's rows for another; if a
 * second length-growing weapon ever lands, `tempFor()` needs generalising (it hardcodes INGR_SPEAR)
 * and the gate needs that weapon's own silhouette. Other skills — shot multipliers, knock — need NO
 * baking at all: they are data on a row plus a hook, with no covering to re-pack.
 */
import { readFileSync, writeFileSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const CANON = join(root, 'uploads', 'spinclash-preview.html');
const WRITE = process.argv.includes('--write');
const _ei = process.argv.indexOf('--emit');
const EMIT = _ei >= 0 ? process.argv[_ei + 1] : null;   /* write the block to a file, touch nothing */
const VERIFY = process.argv.includes('--verify');
const BEGIN = '  // LEN_CIRCLES BEGIN — generated by .qa/lengrow-bake.mjs, never hand-edit';
const END = '  // LEN_CIRCLES END';

/* ---------- read the growth parameters out of the canonical itself ---------- */
function fakeEl() {
  const t = function () {};
  return new Proxy(t, {
    get(x, p) { if (p === Symbol.toPrimitive) return () => 0; if (!(p in x)) x[p] = fakeEl(); return x[p]; },
    set(x, p, v) { x[p] = v; return true; },
    apply() { return fakeEl(); },
  });
}
const src = readFileSync(CANON, 'utf8');
const a = src.indexOf('<script>'), b = src.indexOf('</script>', a);
let body = src.slice(a + 8, b);
const opener = '(function () {';
body = body.slice(body.indexOf(opener) + opener.length);
body = body.slice(0, body.lastIndexOf('})();'));
const api = new Function('document', 'window', 'performance', 'requestAnimationFrame', 'console',
  /* typeof-guard: a canonical predating LEN_STEPS_TOP would throw a ReferenceError on a bare
   * reference, and `typeof` on an undeclared identifier is the one safe way to ask. */
  body + '\n;return { WEAPONS, LEN_STEPS, LEN_STEPS_TOP: typeof LEN_STEPS_TOP === "undefined" ? 0 : LEN_STEPS_TOP };')(
  { getElementById: () => fakeEl(), createElement: () => fakeEl(), querySelectorAll: () => [], addEventListener: () => {}, activeElement: null },
  { devicePixelRatio: 1, innerWidth: 1200, innerHeight: 900, addEventListener: () => {} },
  { now: () => 0 }, () => 0, console);

const GROWERS = Object.keys(api.WEAPONS).filter(id => api.WEAPONS[id].trait && api.WEAPONS[id].trait.len);
/* --steps N: probe a ladder TALLER than the canonical's (feasibility check for a raised cap).
 * Read-only by construction: --write refuses an override, because splicing N rows under a
 * canonical whose LEN_STEPS is something else would trip the boot guard on the next load. */
const _si = process.argv.indexOf('--steps');
const STEPS_OVERRIDE = _si >= 0 ? parseInt(process.argv[_si + 1], 10) : 0;
if (STEPS_OVERRIDE && (!Number.isInteger(STEPS_OVERRIDE) || STEPS_OVERRIDE < 1)) {
  console.error(`lengrow-bake: --steps needs a positive integer (got ${process.argv[_si + 1]})`); process.exit(2);
}
if (STEPS_OVERRIDE && WRITE) {
  console.error('lengrow-bake: --steps cannot be combined with --write — splicing N rows under a canonical that declares a different top would trip the boot guard on the next load. --emit is allowed (it touches no canonical); re-run without --steps afterwards so the provenance line reports the real top.'); process.exit(2);
}
/* Bake to the TOP of the ladder: every grown step needs its own baked covering. Since
 * nocombo-r34 (2026-10-31) the cap is UNIFORM — the per-fighter `skill.lenSteps` addend was
 * retired by the owner's no-combos ruling — so the top is LEN_STEPS for every holder. The
 * typeof-guarded LEN_STEPS_TOP probe stays for canonicals that predate the retirement; on the
 * current canonical it is undefined and the fallback to LEN_STEPS always wins. */
const STEPS = STEPS_OVERRIDE || api.LEN_STEPS_TOP || api.LEN_STEPS;
if (GROWERS.length !== 1 || GROWERS[0] !== 'spear') {
  console.error(`lengrow-bake: expected exactly one growing weapon (spear), found [${GROWERS.join(', ')}] — this tool bakes the spear only; extend it deliberately if that changes.`);
  process.exit(2);
}
const W = api.WEAPONS.spear;
const RATE = W.trait.len, LENJ = W.lenJ;
/* Provenance names the BUILD, not a date: this sandbox's clock runs ahead of the owner's local
 * date (a recorded trap in this project), so `new Date()` here would bake a wrong day into the
 * canonical. The build stamp is read from the file the rows are baked for, so it cannot drift. */
const STAMP = (/<title>spinclash preview \u2014 build ([^<]+)<\/title>/.exec(src) || [])[1] || 'unknown';
console.log(`lengrow-bake — spear, read from the canonical: trait.len ${RATE} (${(RATE * 100).toFixed(2)}%/hit), lenJ ${LENJ.toFixed(6)}, LEN_STEPS ${api.LEN_STEPS}${STEPS_OVERRIDE ? ` (PROBED AT ${STEPS} via --steps)` : ''}, build ${STAMP}`);
console.log(`  top-step tip growth +${((Math.pow(1 + RATE, STEPS) - 1) * 100).toFixed(2)}% · tip/J ${(1 / LENJ).toFixed(6)}`);

/* ---------- the stretch, injected post-normalisation (same map as the boot ladder) ---------- */
function tempFor(k, out) {
  const lines = readFileSync(CANON, 'utf8').split('\n');
  const ns = lines.findIndex(l => l.includes('for (const P of [INGR_HAMMER'));
  if (ns < 0) throw new Error('the :452-455 LT normalisation loop was not found — this tool is stale');
  let ne = ns; while (lines[ne].trim() !== '}') ne++;
  const wi = lines.findIndex(l => l.trim().startsWith('const WEAPON_IDS ='));
  lines[wi] = "  const WEAPON_IDS = ['spear'];";           // bake/audit the spear only
  lines.splice(ne + 1, 0,
    `  /* lengrow-bake injection: the step's rigid d-stretch, applied post-normalisation */`,
    `  (function () { const k = ${k}; let md = 0;`,
    `    for (const pl of INGR_SPEAR.polys) for (const pts of pl.subs) for (const q of pts) md = Math.max(md, q[0]);`,
    `    const J = md * ${LENJ};`,
    `    for (const pl of INGR_SPEAR.polys) for (const pts of pl.subs) for (const q of pts)`,
    `      q[0] = (q[0] <= J ? q[0] * k : q[0] + (k - 1) * J);`,
    `  })();`);
  writeFileSync(out, lines.join('\n'));
}

const run = (args) => { try { return execFileSync(process.execPath, args, { encoding: 'utf8', maxBuffer: 1 << 26, cwd: root }); } catch (e) { return (e.stdout || '') + (e.stderr || ''); } };
const ROW = /^\s*spear:\s*\[\{"d":.*$/m;
const TMP = join(root, 'scratch', '.lengrow-bake-temp.html');

const rows = [], meta = [];
for (let s = 1; s <= STEPS; s++) {
  const tipK = Math.pow(1 + RATE, s);
  const k = 1 + (tipK - 1) / LENJ;                 // identical in INGR and booted space (degree-1 homogeneous)
  tempFor(k, TMP);
  const bake = run([join(here, 'bake-rows.mjs'), 'scratch/.lengrow-bake-temp.html', 'spear']);
  const hit = ROW.exec(readFileSync(TMP, 'utf8'));
  if (!hit) { console.error(`step ${s}: bake-rows produced no spear row.\n${bake.split('\n').slice(-8).join('\n')}`); process.exit(2); }
  const parsed = JSON.parse(hit[0].trim().replace(/^spear:\s*/, '').replace(/,\s*$/, ''));
  rows.push(parsed);
  meta.push({ s, tipK, k, n: parsed.length, minR: Math.min(...parsed.map(c => c.r)) });
  console.log(`  step ${String(s).padStart(2)}  tipK ${tipK.toFixed(4)}  k ${k.toFixed(4)}  ->  ${String(parsed.length).padStart(2)} circles, minR ${Math.min(...parsed.map(c => c.r)).toFixed(2)}`);
}

/* ---------- emit the block ---------- */
const block = [BEGIN,
  `  /* One re-packed covering per length-growth step for the spear; step 0 is the shipped`,
  `   * CIRCLES_V2 row and is not listed. Regenerate with \`node .qa/lengrow-bake.mjs --write\`.`,
  `   * Baked for build ${STAMP} at trait.len ${RATE}, lenJ ${LENJ.toFixed(6)}, LEN_STEPS ${STEPS}:`,
  `   * ${meta.map(m => `${m.n}`).join('/')} circles per step, minR ${Math.min(...meta.map(m => m.minR)).toFixed(2)}-${Math.max(...meta.map(m => m.minR)).toFixed(2)}. */`,
  `  const LEN_CIRCLES = {`,
  `    spear: [`,
  ...rows.map((r, i) => `      ${JSON.stringify(r)},   /* step ${i + 1}: tipK ${meta[i].tipK.toFixed(4)}, k ${meta[i].k.toFixed(4)} */`),
  `    ],`,
  `  };`,
  END];

if (EMIT) {
  writeFileSync(EMIT, block.join('\n') + '\n');
  console.log(`\n--emit: wrote ${block.length} lines, ${(block.join('\n').length / 1024).toFixed(1)} KB to ${EMIT} — the canonical was NOT touched.`);
  rmSync(TMP, { force: true });
  process.exit(0);
}

if (!WRITE && !VERIFY) {
  console.log(`\n--- dry run: ${block.length} lines, ${(block.join('\n').length / 1024).toFixed(1)} KB ---`);
  console.log(block.slice(0, 8).join('\n'));
  console.log('  ...');
  rmSync(TMP, { force: true });
  process.exit(0);
}

/* ---------- verify: gate every step's own row against its own art ---------- */
if (VERIFY) {
  console.log('\nverify — each baked row gated against that step\'s own stretched art:');
  console.log('  step   tipK      k     n   minR    poke      miss    verdict');
  let bad = 0;
  for (let s = 1; s <= STEPS; s++) {
    tempFor(meta[s - 1].k, TMP);
    run([join(here, 'bake-rows.mjs'), 'scratch/.lengrow-bake-temp.html', 'spear']);
    const gate = run([join(here, 'inscribe.mjs'), 'scratch/.lengrow-bake-temp.html']);
    const m = gate.split('\n').find(l => /^spear\s/.test(l));
    if (!m) { console.log(`  ${String(s).padStart(4)}   BOOT/RUN FAILURE\n${gate.split('\n').slice(0, 5).join('\n')}`); bad++; continue; }
    const num = re => { const x = re.exec(m); return x ? x[1] : 'NaN'; };
    const poke = num(/poke=([+-]?[\d.]+)/), miss = +num(/miss=([\d.]+)/);
    const inf = /poke=\+Infinity/.test(m);
    const fail = inf || +poke > 0.12 || miss > 4.6;
    if (fail) bad++;
    console.log(`  ${String(s).padStart(4)}  ${meta[s - 1].tipK.toFixed(4)}  ${meta[s - 1].k.toFixed(4)}  ${String(meta[s - 1].n).padStart(3)}  ${num(/minR=\s*([\d.]+)/).padStart(5)}  ${(poke + 'px').padStart(7)}  ${(miss.toFixed(2) + 'px').padStart(7)}   ${fail ? 'GATE FAIL' : 'gate PASS'}`);
  }
  rmSync(TMP, { force: true });
  console.log(bad === 0 ? `\n  ALL ${STEPS} STEPS PASS the house gate on their own baked rows.` : `\n  ${bad} STEP(S) FAILED — do not write.`);
  if (bad) process.exit(1);
  if (!WRITE) process.exit(0);
}

/* ---------- splice, preserving every other byte ---------- */
const cur = readFileSync(CANON, 'utf8');
const lines = cur.split('\n');
const bi = lines.findIndex(l => l.trim() === BEGIN.trim());
const ei = lines.findIndex(l => l.trim() === END.trim());
let outLines;
if (bi >= 0 && ei > bi) {
  outLines = [...lines.slice(0, bi), ...block, ...lines.slice(ei + 1)];
  console.log(`\nreplacing the existing LEN_CIRCLES block (lines ${bi + 1}-${ei + 1}) with ${block.length} lines`);
} else {
  if (bi >= 0 || ei >= 0) { console.error('one LEN_CIRCLES marker found without the other — refusing to guess'); process.exit(2); }
  const at = lines.findIndex(l => l.trim().startsWith('const LEN_STEPS ='));
  if (at < 0) { console.error('`const LEN_STEPS =` not found — nowhere to insert'); process.exit(2); }
  outLines = [...lines.slice(0, at), ...block, '', ...lines.slice(at)];
  console.log(`\ninserting the ${block.length}-line LEN_CIRCLES block before \`const LEN_STEPS =\` (line ${at + 1})`);
}
const before = cur.length;
writeFileSync(CANON, outLines.join('\n'));
const after = readFileSync(CANON, 'utf8');
console.log(`wrote ${CANON.split('/').pop()}: ${before} -> ${after.length} bytes, ${lines.length} -> ${after.split('\n').length} lines`);
rmSync(TMP, { force: true });
